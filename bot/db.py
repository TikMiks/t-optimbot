class _SqliteBackend:
    kind = "sqlite"

    def __init__(self, path: Path) -> None:
        self._path = Path(path)
        self._conn: aiosqlite.Connection | None = None

    @property
    def conn(self) -> aiosqlite.Connection:
        if self._conn is None:
            raise RuntimeError("Database.connect() ещё не вызван")
        return self._conn

    def describe(self) -> str:
        return f"SQLite {self._path}"

    async def connect(self) -> None:
        self._path.parent.mkdir(parents=True, exist_ok=True)
        self._conn = await aiosqlite.connect(self._path)
        self._conn.row_factory = aiosqlite.Row
        await self._conn.execute("PRAGMA journal_mode=WAL")
        await self._conn.execute("PRAGMA foreign_keys=ON")
        await self._conn.executescript(SQLITE_SCHEMA)
        await self._migrate()
        await self._conn.commit()

    async def _migrate(self) -> None:
        """Добавляет колонки, которых нет в уже существующей базе."""
        await self._ensure_column("sales", "external_id", "TEXT")
        await self._ensure_column("sales", "is_reverted", "INTEGER NOT NULL DEFAULT 0")
        await self._ensure_column(
            "promos", "hidden_in_report", "INTEGER NOT NULL DEFAULT 0"
        )
        await self._drop_column("promos", "discount_percent")
        await self.conn.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS idx_sales_external "
            "ON sales(external_id) WHERE external_id IS NOT NULL"
        )

    async def _columns(self, table: str) -> set[str]:
        async with self.conn.execute(f"PRAGMA table_info({table})") as cur:
            return {row["name"] for row in await cur.fetchall()}

    async def _ensure_column(self, table: str, column: str, ddl: str) -> None:
        if column not in await self._columns(table):
            await self.conn.execute(f"ALTER TABLE {table} ADD COLUMN {column} {ddl}")

    async def _drop_column(self, table: str, column: str) -> None:
        if column in await self._columns(table):
            await self.conn.execute(f"ALTER TABLE {table} DROP COLUMN {column}")

    async def close(self) -> None:
        if self._conn is not None:
            await self._conn.close()
            self._conn = None

    async def fetchone(self, sql: str, params: Sequence[Any] = ()) -> Row | None:
        async with self.conn.execute(sql, tuple(params)) as cur:
            row = await cur.fetchone()
        return dict(row) if row is not None else None

    async def fetchall(self, sql: str, params: Sequence[Any] = ()) -> list[Row]:
        async with self.conn.execute(sql, tuple(params)) as cur:
            rows = await cur.fetchall()
        return [dict(row) for row in rows]

    async def execute(self, sql: str, params: Sequence[Any] = ()) -> None:
        try:
            await self.conn.execute(sql, tuple(params))
        except aiosqlite.IntegrityError as exc:
            raise IntegrityError(str(exc)) from exc
        await self.conn.commit()

    async def insert(self, sql: str, params: Sequence[Any] = ()) -> int:
        try:
            cursor = await self.conn.execute(sql, tuple(params))
        except aiosqlite.IntegrityError as exc:
            raise IntegrityError(str(exc)) from exc
        await self.conn.commit()
        return int(cursor.lastrowid)


_PLACEHOLDER_RE = re.compile(r"\?")
# Параметры строки подключения, которые понимает libpq, но не asyncpg.
_UNSUPPORTED_DSN_PARAMS = {"channel_binding", "pgbouncer", "connection_limit"}


def _to_postgres_sql(sql: str) -> str:
    counter = 0

    def repl(_: re.Match[str]) -> str:
        nonlocal counter
        counter += 1
        return f"${counter}"

    return _PLACEHOLDER_RE.sub(repl, sql)


def _clean_dsn(url: str) -> str:
    parts = urlsplit(url)
    query = [
        (key, value)
        for key, value in parse_qsl(parts.query, keep_blank_values=True)
        if key not in _UNSUPPORTED_DSN_PARAMS
    ]
    scheme = "postgresql" if parts.scheme in {"postgres", "postgresql"} else parts.scheme
    return urlunsplit((scheme, parts.netloc, parts.path, urlencode(query), parts.fragment))


def _plain(value: Any) -> Any:
    # SUM() по BIGINT в Postgres возвращает NUMERIC — приводим к int, как в SQLite.
    if isinstance(value, Decimal):
        return int(value)
    return value


def _pg_row(record: Mapping[str, Any]) -> Row:
    return {key: _plain(value) for key, value in record.items()}


class _PostgresBackend:
    kind = "postgres"

    def __init__(self, url: str) -> None:
        self._url = _clean_dsn(url)
        self._pool = None

    @property
    def pool(self):
        if self._pool is None:
            raise RuntimeError("Database.connect() ещё не вызван")
        return self._pool

    def describe(self) -> str:
        parts = urlsplit(self._url)
        return f"Postgres {parts.hostname}{parts.path}"

    async def connect(self) -> None:
        import asyncpg

        # statement_cache_size=0 — иначе ломается за пулерами PgBouncer/Supavisor.
        self._pool = await asyncpg.create_pool(
            self._url,
            min_size=1,
            max_size=5,
            statement_cache_size=0,
            command_timeout=30,
        )
        async with self.pool.acquire() as conn:
            await conn.execute(POSTGRES_SCHEMA)
            await conn.execute(
                "CREATE UNIQUE INDEX IF NOT EXISTS idx_sales_external "
                "ON sales(external_id) WHERE external_id IS NOT NULL"
            )

    async def close(self) -> None:
        if self._pool is not None:
            await self._pool.close()
            self._pool = None

    async def fetchone(self, sql: str, params: Sequence[Any] = ()) -> Row | None:
        record = await self.pool.fetchrow(_to_postgres_sql(sql), *params)
        return _pg_row(record) if record is not None else None

    async def fetchall(self, sql: str, params: Sequence[Any] = ()) -> list[Row]:
        records = await self.pool.fetch(_to_postgres_sql(sql), *params)
        return [_pg_row(record) for record in records]

    async def execute(self, sql: str, params: Sequence[Any] = ()) -> None:
        import asyncpg

        try:
            await self.pool.execute(_to_postgres_sql(sql), *params)
        except asyncpg.UniqueViolationError as exc:
            raise IntegrityError(str(exc)) from exc

    async def insert(self, sql: str, params: Sequence[Any] = ()) -> int:
        import asyncpg

        try:
            value = await self.pool.fetchval(
                _to_postgres_sql(sql) + " RETURNING id", *params
            )
        except asyncpg.UniqueViolationError as exc:
            raise IntegrityError(str(exc)) from exc
        return int(value)

    async def reset_sequences(self) -> None:
        """Сдвигает счётчики id после вставки строк с явными id (перенос данных)."""
        for table in TABLES:
            if table == "settings":
                continue
            await self.pool.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)"
            )


