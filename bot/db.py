class Database:
    """Хранилище бота: Postgres, если задан `url`, иначе файл SQLite по `path`."""

    def __init__(self, path: Path | None = None, url: str | None = None) -> None:
        if url:
            self._backend: _SqliteBackend | _PostgresBackend = _PostgresBackend(url)
        elif path is not None:
            self._backend = _SqliteBackend(path)
        else:
            raise ValueError("Нужен путь к SQLite или DATABASE_URL")

    @property
    def kind(self) -> str:
        return self._backend.kind

    def describe(self) -> str:
        return self._backend.describe()

    async def connect(self) -> None:
        await self._backend.connect()
        if await self.get_setting(REPORT_SINCE_KEY) is None:
            await self.set_setting(REPORT_SINCE_KEY, str(DEFAULT_REPORT_SINCE))

    async def close(self) -> None:
        await self._backend.close()

    async def _one(self, sql: str, params: Sequence[Any] = ()) -> Row | None:
        return await self._backend.fetchone(sql, params)

    async def _all(self, sql: str, params: Sequence[Any] = ()) -> list[Row]:
        return await self._backend.fetchall(sql, params)

    async def _exec(self, sql: str, params: Sequence[Any] = ()) -> None:
        await self._backend.execute(sql, params)

    async def _insert(self, sql: str, params: Sequence[Any] = ()) -> int:
        return await self._backend.insert(sql, params)

    # ---------------------------------------------------------------- promos

    async def create_promo(self, code: str, reward: int) -> Promo:
        try:
            promo_id = await self._insert(
                """
                INSERT INTO promos (code, reward, bind_token, created_at)
                VALUES (?, ?, ?, ?)
                """,
                (code, reward, new_token(), now_ts()),
            )
        except IntegrityError as exc:
            raise PromoCodeExists(code) from exc
        promo = await self.get_promo_by_id(promo_id)
        assert promo is not None
        return promo

    async def get_promo_by_id(self, promo_id: int) -> Promo | None:
        row = await self._one("SELECT * FROM promos WHERE id = ?", (promo_id,))
        return Promo.from_row(row) if row else None

    async def get_promo_by_code(self, code: str) -> Promo | None:
        row = await self._one("SELECT * FROM promos WHERE code = ?", (code,))
        return Promo.from_row(row) if row else None

    async def get_promo_by_token(self, token: str) -> Promo | None:
        row = await self._one("SELECT * FROM promos WHERE bind_token = ?", (token,))
        return Promo.from_row(row) if row else None

    async def list_promos(self) -> list[Promo]:
        rows = await self._all("SELECT * FROM promos ORDER BY code")
        return [Promo.from_row(row) for row in rows]

    async def list_promos_by_owner(self, owner_id: int) -> list[Promo]:
        rows = await self._all(
            "SELECT * FROM promos WHERE owner_id = ? ORDER BY code", (owner_id,)
        )
        return [Promo.from_row(row) for row in rows]

    async def set_reward(self, promo_id: int, reward: int) -> None:
        await self._exec("UPDATE promos SET reward = ? WHERE id = ?", (reward, promo_id))

    async def set_active(self, promo_id: int, is_active: bool) -> None:
        await self._exec(
            "UPDATE promos SET is_active = ? WHERE id = ?", (int(is_active), promo_id)
        )

    async def set_hidden_in_report(self, promo_id: int, hidden: bool) -> None:
        await self._exec(
            "UPDATE promos SET hidden_in_report = ? WHERE id = ?",
            (int(hidden), promo_id),
        )

    async def delete_promo(self, promo_id: int) -> None:
        await self._exec("DELETE FROM promos WHERE id = ?", (promo_id,))

    async def reset_bind_token(self, promo_id: int) -> str:
        token = new_token()
        await self._exec(
            "UPDATE promos SET bind_token = ? WHERE id = ?", (token, promo_id)
        )
        return token

    async def bind_owner(
        self, promo_id: int, owner_id: int, username: str | None, name: str | None
    ) -> None:
        """Привязывает владельца и гасит одноразовый токен."""
        await self._exec(
            """
            UPDATE promos
               SET owner_id = ?, owner_username = ?, owner_name = ?,
                   bound_at = ?, bind_token = NULL
             WHERE id = ?
            """,
            (owner_id, username, name, now_ts(), promo_id),
        )

    async def unbind_owner(self, promo_id: int) -> str:
        token = new_token()
        await self._exec(
            """
            UPDATE promos
               SET owner_id = NULL, owner_username = NULL, owner_name = NULL,
                   bound_at = NULL, bind_token = ?
             WHERE id = ?
            """,
            (token, promo_id),
        )
        return token

    async def refresh_owner_profile(
        self, owner_id: int, username: str | None, name: str | None
    ) -> None:
        await self._exec(
            "UPDATE promos SET owner_username = ?, owner_name = ? WHERE owner_id = ?",
            (username, name, owner_id),
        )

    # ----------------------------------------------------------------- sales

    async def add_sale(
        self,
        promo_id: int,
        reward: int,
        amount: int | None = None,
        note: str | None = None,
        created_by: int | None = None,
        external_id: str | None = None,
        created_at: int | None = None,
    ) -> int:
        """Записывает продажу. Повтор `external_id` бросает IntegrityError."""
        return await self._insert(
            """
            INSERT INTO sales (
                promo_id, amount, reward, note, created_by, created_at, external_id
            )
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (promo_id, amount, reward, note, created_by, created_at or now_ts(), external_id),
        )

    async def delete_last_sale(self, promo_id: int) -> SaleRecord | None:
        row = await self._one(
            f"""
            SELECT {_SALE_COLUMNS}
              FROM sales
             WHERE promo_id = ? AND {SALE_ACTIVE}
             ORDER BY id DESC
             LIMIT 1
            """,
            (promo_id,),
        )
        if row is None:
            return None
        await self._exec("DELETE FROM sales WHERE id = ?", (row["id"],))
        return SaleRecord.from_row(row)

    async def revert_sale(self, sale_id: int) -> SaleRecord | None:
        row = await self._one(
            f"SELECT {_SALE_COLUMNS} FROM sales WHERE id = ?", (sale_id,)
        )
        if row is None:
            return None
        if not row["is_reverted"]:
            await self._exec("UPDATE sales SET is_reverted = 1 WHERE id = ?", (sale_id,))
        record = SaleRecord.from_row(row)
        record.is_reverted = True
        return record

    async def get_active_sale_by_external_id(
        self, external_id: str
    ) -> tuple[int, int, int] | None:
        """Живая продажа по id транзакции: (sale_id, promo_id, reward)."""
        row = await self._one(
            """
            SELECT id, promo_id, reward
              FROM sales
             WHERE external_id = ? AND COALESCE(is_reverted, 0) = 0
            """,
            (external_id,),
        )
        if row is None:
            return None
        return int(row["id"]), int(row["promo_id"]), int(row["reward"])

    async def recent_sales(self, promo_id: int, limit: int = 10) -> list[SaleRecord]:
        rows = await self._all(
            f"""
            SELECT {_SALE_COLUMNS}
              FROM sales
             WHERE promo_id = ? AND {SALE_ACTIVE} AND created_at > ?
             ORDER BY created_at DESC, id DESC
             LIMIT ?
            """,
            (promo_id, await self.get_report_since(), limit),
        )
        return [SaleRecord.from_row(row) for row in rows]

